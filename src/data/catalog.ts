export type FamilyId = (typeof FAMILIES)[number]["id"];

export type Overlay = "nist-moderate" | "cnssi-1253" | "privacy" | "dod-rmf";

export type ControlCatalogItem = {
  id: string;
  family: FamilyId;
  title: string;
  enhancement: boolean;
  overlays: Overlay[];
  policyControl: boolean;
};

function c(
  id: string,
  title: string,
  overlays: Overlay[] = ["nist-moderate", "cnssi-1253", "dod-rmf"],
): ControlCatalogItem {
  const family = id.split("-")[0] as FamilyId;
  const enhancement = /\([0-9]+\)/.test(id);
  const policyControl = /^[A-Z]{2,3}-1$/.test(id);
  return { id, family, title, enhancement, overlays, policyControl };
}

